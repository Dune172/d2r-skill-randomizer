// Command namedump prints the items a D2R Randomizer slot can receive and every check it
// can hold, for the list on the site's /archipelago page.
//
// scripts/gen-ap-names.mjs writes this to src/lib/archipelago/ap-names.json, and its
// --check mode fails CI when the file is stale. The names themselves are proved equal to
// the apworld's by scripts/verify-ap-ids.mjs, so the page never names a check the room
// does not have.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"github.com/Dune172/d2r-skill-randomizer/tools/ap-client/internal/ids"
)

type item struct {
	Name  string `json:"name"`
	Group string `json:"group"`
}

func main() {
	// Only what a room can place. Training Fragments and runes keep their ids but are
	// never in the pool.
	items := []item{
		{ids.SkillPointItem, "Skill Points"},
		{ids.StatPointsItem, "Stat Points"},
		{ids.HoradricKeyItem, "Keys"},
		{ids.GoldItem, "Filler"},
	}
	for _, name := range ids.Traps {
		items = append(items, item{name, "Traps"})
	}

	// Each location as [id, name, kind, difficulty, act, town]: compact, because the page
	// loads the whole list.
	var locations [][]any
	for off := 0; off < ids.LocationsTotal(); off++ {
		id := int64(ids.LocationBase + off)
		info, okInfo := ids.Locate(id)
		name, okName := ids.LocationName(id)
		if !okInfo || !okName {
			fmt.Fprintf(os.Stderr, "location %d does not resolve\n", id)
			os.Exit(1)
		}
		town := 0
		if ids.IsTownCheck(info) {
			town = 1
		}
		locations = append(locations, []any{id, name, info.Kind.String(), info.Difficulty, info.Act, town})
	}

	out, err := json.Marshal(map[string]any{
		"note":       "GENERATED by scripts/gen-ap-names.mjs from tools/ap-client/cmd/namedump. Do not edit by hand.",
		"levelCaps":  ids.LevelCaps,
		"items":      items,
		"locations":  locations,
		"difficulty": ids.DifficultyNames,
	})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println(string(out))
}
