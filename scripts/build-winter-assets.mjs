// ── Vector helpers ───────────────────────────────────────────────────────────
const add3 = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const mul3 = (a, k) => [a[0] * k, a[1] * k, a[2] * k];
const dot3 = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross3 = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const norm3 = v => { const l = Math.hypot(...v) || 1; return v.map(x => x / l); };
const rotY = (p, a) => [Math.cos(a) * p[0] + Math.sin(a) * p[2], p[1], -Math.sin(a) * p[0] + Math.cos(a) * p[2]];
const rotZ = (p, a) => [Math.cos(a) * p[0] - Math.sin(a) * p[1], Math.sin(a) * p[0] + Math.cos(a) * p[1], p[2]];
const rotX = (p, a) => [p[0], Math.cos(a) * p[1] - Math.sin(a) * p[2], Math.sin(a) * p[1] + Math.cos(a) * p[2]];
// A UV rectangle in the atlas and a point inside it.
const rect = (u0, u1, v0, v1) => ({ u0, u1, v0, v1 });
// Inset from the region edges so BC3 blocks and filtering never pick up the
// neighbouring region.
const INSET = 4 / 512;
const at = (r, s, t) => {
  const iu = Math.min(INSET, (r.u1 - r.u0) / 4), iv = Math.min(INSET, (r.v1 - r.v0) / 4);
  return [r.u0 + iu + (r.u1 - r.u0 - 2 * iu) * s, r.v0 + iv + (r.v1 - r.v0 - 2 * iv) * t];
};

// ── Mesh builder ─────────────────────────────────────────────────────────────
class Mesh {
  constructor() { this.v = []; this.vt = []; this.vn = []; this.f = []; }
  vert(p, uv, n) { this.v.push(p); this.vt.push(uv); this.vn.push(norm3(n)); return this.v.length; }
  // Winding follows the vertex normals (counter-clockwise around them).
  tri(a, b, c) {
    const [pa, pb, pc] = [a, b, c].map(i => this.v[i - 1]);
    const g = cross3(sub3(pb, pa), sub3(pc, pa));
    if (Math.hypot(...g) < 1e-12) return;
    const n = add3(add3(this.vn[a - 1], this.vn[b - 1]), this.vn[c - 1]);
    this.f.push(dot3(g, n) >= 0 ? [a, b, c] : [a, c, b]);
  }
  quad(a, b, c, d) { this.tri(a, b, c); this.tri(a, c, d); }
  // Parametric surface grid: fn(s, t) -> { p, n }, s wraps when `wrap`.
  grid(fn, ns, nt, region) {
    const idx = [];
    for (let j = 0; j <= nt; j++) {
      const row = [];
      for (let i = 0; i <= ns; i++) {
        const s = i / ns, t = j / nt, { p, n } = fn(s, t);
        row.push(this.vert(p, at(region, s, t), n));
      }
      idx.push(row);
    }
    for (let j = 0; j < nt; j++) for (let i = 0; i < ns; i++) this.quad(idx[j][i], idx[j][i + 1], idx[j + 1][i + 1], idx[j + 1][i]);
  }
  obj(title) {
    const lines = [`# ${title} — generated by scripts/build-winter-assets.mjs`];
    for (const p of this.v) lines.push(`v ${p.map(x => x.toFixed(6)).join(' ')}`);
    for (const t of this.vt) lines.push(`vt ${t.map(x => x.toFixed(6)).join(' ')}`);
    for (const n of this.vn) lines.push(`vn ${n.map(x => x.toFixed(6)).join(' ')}`);
    lines.push(`g ${title.replace(/\W+/g, '_')}`);
    for (const t of this.f) lines.push(`f ${t.map(i => `${i}/${i}/${i}`).join(' ')}`);
    return lines.join('\n') + '\n';
  }
}

// Ellipsoid centred at c; t runs top (0) to bottom (1). `xf` transforms
// local points/normals (rotation) before translation.
function ellipsoid(m, c, [rx, ry, rz], region, ns = 32, nt = 16, xf = p => p, bump = () => 1) {
  m.grid((s, t) => {
    const th = s * 2 * Math.PI, ph = t * Math.PI, k = bump(th, ph);
    const u = [Math.sin(ph) * Math.cos(th), Math.cos(ph), Math.sin(ph) * Math.sin(th)];
    const p = [rx * u[0] * k, ry * u[1] * k, rz * u[2] * k];
    const n = [u[0] / rx, u[1] / ry, u[2] / rz];
    return { p: add3(c, xf(p)), n: xf(n) };
  }, ns, nt, region);
}

// Tube along a polyline with per-point radii (0 = pointed tip), closed with a
// cap at each non-zero end. t runs along the path, s around it.
function tube(m, pts, radii, region, seg = 8, caps = true, phase = 0) {
  const frames = pts.map((p, k) => {
    const d = norm3(sub3(pts[Math.min(k + 1, pts.length - 1)], pts[Math.max(k - 1, 0)]));
    const ref = Math.abs(d[1]) < 0.9 ? [0, 1, 0] : [1, 0, 0];
    const a = norm3(cross3(d, ref)), b = cross3(d, a);
    return { p, d, a, b };
  });
  const L = pts.length - 1;
  m.grid((s, t) => {
    const k = Math.min(L, Math.round(t * L)), f = frames[k], ang = s * 2 * Math.PI + phase;
    const dir = add3(mul3(f.a, Math.cos(ang)), mul3(f.b, Math.sin(ang)));
    return { p: add3(f.p, mul3(dir, radii[k])), n: dir };
  }, seg, L, region);
  if (!caps) return;
  for (const k of [0, L]) {
    if (radii[k] < 1e-6) continue;
    const f = frames[k], out = k === 0 ? mul3(f.d, -1) : f.d;
    const centre = m.vert(f.p, at(region, 0.5, k === 0 ? 0 : 1), out);
    const ring = [];
    for (let i = 0; i <= seg; i++) {
      const ang = (i / seg) * 2 * Math.PI + phase;
      ring.push(m.vert(add3(f.p, mul3(add3(mul3(f.a, Math.cos(ang)), mul3(f.b, Math.sin(ang))), radii[k])), at(region, i / seg, k === 0 ? 0 : 1), out));
    }
    for (let i = 0; i < seg; i++) m.tri(centre, ring[i], ring[i + 1]);
  }
}

// Torus in the XZ plane around c (major R, minor r), then rotated by xf.
function torus(m, c, R, r, region, ns = 32, nt = 10, xf = p => p, squashY = 1) {
  m.grid((s, t) => {
    const a = s * 2 * Math.PI, b = t * 2 * Math.PI;
    const ring = [Math.cos(a), 0, Math.sin(a)];
    const n = [Math.cos(b) * ring[0], Math.sin(b), Math.cos(b) * ring[2]];
    const p = [(R + r * Math.cos(b)) * ring[0], r * Math.sin(b) * squashY, (R + r * Math.cos(b)) * ring[2]];
    return { p: add3(c, xf(p)), n: xf([n[0], n[1] / squashY, n[2]]) };
  }, ns, nt, region);
}

// Axis-aligned box (before yaw) with its base centred on c. Faces map to
// `side` (u horizontal, v up) and `top`/`bottom` tiles, subdivided `div`
// times so the ribbon texture stays straight after BC3.
function box(m, c, [w, h, d], yaw, { side, top, bottom = top }, div = 2) {
  const faces = [
    { n: [0, 0, 1], o: [-w / 2, 0, d / 2], u: [w, 0, 0], v: [0, h, 0], tile: side },
    { n: [0, 0, -1], o: [w / 2, 0, -d / 2], u: [-w, 0, 0], v: [0, h, 0], tile: side },
    { n: [1, 0, 0], o: [w / 2, 0, d / 2], u: [0, 0, -d], v: [0, h, 0], tile: side },
    { n: [-1, 0, 0], o: [-w / 2, 0, -d / 2], u: [0, 0, d], v: [0, h, 0], tile: side },
    { n: [0, 1, 0], o: [-w / 2, h, d / 2], u: [w, 0, 0], v: [0, 0, -d], tile: top },
    { n: [0, -1, 0], o: [-w / 2, 0, -d / 2], u: [w, 0, 0], v: [0, 0, d], tile: bottom },
  ];
  for (const f of faces) {
    m.grid((s, t) => ({ p: add3(c, rotY(add3(add3(f.o, mul3(f.u, s)), mul3(f.v, t)), yaw)), n: rotY(f.n, yaw) }), div, div, f.tile);
  }
}

// ── Snowman ──────────────────────────────────────────────────────────────────
// About 2 units tall at scale 1 (sackpile01 allows ±3.52).
const SM = {
  SNOW: rect(0, 1, 0.4, 1),
  CARROT: rect(0, 0.5, 0.32, 0.4),
  TWIG: rect(0.5, 1, 0.32, 0.4),
  SCARF: rect(0, 1, 0.2, 0.32),
  HAT: rect(0, 0.5, 0.08, 0.2),
  BAND: rect(0.5, 0.75, 0.08, 0.2),
  COAL: rect(0.75, 1, 0.08, 0.2),
};

function snowman() {
  const m = new Mesh();
  // Lumpy snowballs: a little low-frequency wobble so they look packed by hand.
  const lumpy = seed => (th, ph) => 1 + 0.025 * Math.sin(3 * th + seed) * Math.sin(2 * ph + seed * 0.7) + 0.015 * Math.sin(5 * th + 2 * ph + seed);
  const balls = [
    { c: [0, 0.4, 0], r: [0.5, 0.44, 0.5] },
    { c: [0, 1.0, 0], r: [0.36, 0.33, 0.36] },
    { c: [0, 1.48, 0], r: [0.25, 0.24, 0.25] },
  ];
  balls.forEach((b, k) => ellipsoid(m, b.c, b.r, SM.SNOW, 36, 18, p => p, lumpy(k * 2.1 + 0.4)));
  const head = balls[2];
  // Coal: eyes, a smile of five, three buttons down the front (+Z).
  const onBall = (b, yawDeg, pitchDeg, out = 0.004) => {
    const th = Math.PI / 2 - (yawDeg * Math.PI) / 180, ph = Math.PI / 2 - (pitchDeg * Math.PI) / 180;
    const u = [Math.sin(ph) * Math.cos(th), Math.cos(ph), Math.sin(ph) * Math.sin(th)];
    return add3(b.c, [u[0] * (b.r[0] + out), u[1] * (b.r[1] + out), u[2] * (b.r[2] + out)]);
  };
  const coal = (p, r) => ellipsoid(m, p, [r, r, r * 0.8], SM.COAL, 8, 5);
  coal(onBall(head, -24, 22), 0.034);
  coal(onBall(head, 24, 22), 0.034);
  for (const [yaw, pitch] of [[-30, -18], [-15, -26], [0, -29], [15, -26], [30, -18]]) coal(onBall(head, yaw, pitch), 0.022);
  for (const pitch of [28, 2, -24]) coal(onBall(balls[1], 0, pitch), 0.036);
  // Carrot nose, pointing forward and a touch down.
  const nose = onBall(head, 0, 4, -0.02);
  tube(m, [nose, add3(nose, [0, -0.01, 0.1]), add3(nose, [0, -0.025, 0.2]), add3(nose, [0, -0.04, 0.28])], [0.045, 0.036, 0.022, 0], SM.CARROT, 10);
  // Twig arms, reaching out and up, each with a small fork.
  for (const side of [-1, 1]) {
    const root = onBall(balls[1], side * 88, 12, -0.06);
    const pts = [root, add3(root, [side * 0.22, 0.08, 0.02]), add3(root, [side * 0.44, 0.2, 0.03]), add3(root, [side * 0.62, 0.34, 0.02])];
    tube(m, pts, [0.032, 0.026, 0.018, 0.006], SM.TWIG, 6);
    const fork = pts[2];
    tube(m, [fork, add3(fork, [side * 0.1, 0.13, 0.02]), add3(fork, [side * 0.14, 0.22, 0.03])], [0.014, 0.01, 0.004], SM.TWIG, 5);
    const fork2 = pts[1];
    tube(m, [fork2, add3(fork2, [side * 0.12, -0.06, 0.04]), add3(fork2, [side * 0.2, -0.08, 0.06])], [0.013, 0.009, 0.004], SM.TWIG, 5);
  }
  // Scarf round the neck, with a tail hanging down the front-left.
  const neckY = 1.27;
  torus(m, [0, neckY, 0], 0.25, 0.065, SM.SCARF, 32, 10, p => p, 0.85);
  const tail0 = [0.12, neckY - 0.02, 0.22];
  tube(m, [tail0, add3(tail0, [0.03, -0.14, 0.07]), add3(tail0, [0.05, -0.3, 0.1]), add3(tail0, [0.06, -0.42, 0.1])], [0.06, 0.055, 0.052, 0.05], SM.SCARF, 8);
  // Top hat, tipped slightly back.
  const tilt = p => rotX(p, -0.12);
  const hatBase = [0, head.c[1] + head.r[1] - 0.035, -0.01];
  const hatPath = (y0, y1, r0, r1, region) => tube(m, [add3(hatBase, tilt([0, y0, 0])), add3(hatBase, tilt([0, y1, 0]))], [r0, r1], region, 20);
  hatPath(0, 0.028, 0.3, 0.3, SM.HAT);        // brim
  hatPath(0.028, 0.09, 0.17, 0.17, SM.BAND);  // band
  hatPath(0.09, 0.3, 0.17, 0.18, SM.HAT);     // crown
  return m;
}

// ── Gift pile ────────────────────────────────────────────────────────────────
// Three wrapped boxes, each wrap colour with a side tile (one vertical ribbon)
// and a top tile (ribbon cross). Bows sample the ribbon at the top tile centre.
const WRAPS = [
  { wrap: [176, 26, 30], ribbon: [236, 190, 72], pattern: 'dots' },   // red, gold ribbon
  { wrap: [24, 104, 58], ribbon: [236, 190, 72], pattern: 'stripes' }, // green, gold ribbon
  { wrap: [232, 228, 214], ribbon: [188, 30, 36], pattern: 'stars' },  // cream, red ribbon
];
const GIFT_SIDE = k => rect(k / 3, (k + 1) / 3, 0.5, 1);
const GIFT_TOP = k => rect(k / 3, (k + 1) / 3, 0, 0.5);
const RIBBON = 0.16; // ribbon width as a fraction of the tile

function gifts() {
  const m = new Mesh();
  const boxes = [
    // The big box's bow would sit inside the small box stacked on it.
    { c: [0, 0, 0], size: [0.56, 0.44, 0.56], yaw: 0.1, k: 0, bow: false },
    { c: [0.5, 0, 0.18], size: [0.4, 0.34, 0.4], yaw: 0.55, k: 1, bow: true },
    { c: [-0.04, 0.44, 0.02], size: [0.3, 0.26, 0.3], yaw: -0.35, k: 2, bow: true },
  ];
  for (const b of boxes) {
    box(m, b.c, b.size, b.yaw, { side: GIFT_SIDE(b.k), top: GIFT_TOP(b.k) }, 4);
    if (!b.bow) continue;
    // Bow: two tilted loops and a knot on the lid.
    const top = add3(b.c, [0, b.size[1], 0]);
    const knot = GIFT_TOP(b.k), [ua, va] = at(knot, 0.49, 0.49), [ub, vb] = at(knot, 0.51, 0.51);
    const solid = rect(ua, ub, va, vb);
    const s = 0.95;
    for (const side of [-1, 1]) {
      torus(m, add3(top, rotY([side * 0.075 * s, 0.05 * s, 0], b.yaw)), 0.07 * s, 0.018 * s, solid, 14, 6,
        p => rotY(rotZ(rotX(p, Math.PI / 2), side * 0.55), b.yaw + Math.PI / 2), 1);
    }
    ellipsoid(m, add3(top, [0, 0.022 * s, 0]), [0.035 * s, 0.03 * s, 0.035 * s], solid, 10, 6);
  }
  return m;
}

// ── Lantern ──────────────────────────────────────────────────────────────────
// Open iron frame (four posts, base, pyramid roof, ring handle) round a
// candle, so the candle flame VFX shows through. About 0.78 units tall.
const LN = { IRON: rect(0, 0.5, 0.5, 1), WAX: rect(0.5, 1, 0.5, 1), GLOW: rect(0, 1, 0, 0.5) };
export const LANTERN_FLAME_Y = 0.27; // candle top, at scale 1

function lantern() {
  const m = new Mesh();
  const W = 0.3, H = 0.5, P = 0.03;
  box(m, [0, 0, 0], [W + 0.06, 0.05, W + 0.06], 0, { side: LN.IRON, top: LN.IRON }, 1);
  for (const [x, z] of [[-1, -1], [-1, 1], [1, -1], [1, 1]]) box(m, [x * W / 2, 0.05, z * W / 2], [P, H, P], 0, { side: LN.IRON, top: LN.IRON }, 1);
  // Thin cross bars half-way up each open side.
  for (const yaw of [0, Math.PI / 2]) for (const s of [-1, 1]) {
    const c = rotY([0, 0.05 + H * 0.12, s * W / 2], yaw);
    box(m, c, [W, 0.02, 0.02], yaw, { side: LN.IRON, top: LN.IRON }, 1);
  }
  box(m, [0, 0.05 + H, 0], [W + 0.05, 0.035, W + 0.05], 0, { side: LN.IRON, top: LN.IRON }, 1);
  // Roof: a 4-sided cone, then the ring handle.
  const roof0 = 0.05 + H + 0.035;
  tube(m, [[0, roof0, 0], [0, roof0 + 0.11, 0], [0, roof0 + 0.16, 0]], [0.25, 0.09, 0], LN.IRON, 4, true, Math.PI / 4);
  torus(m, [0, roof0 + 0.2, 0], 0.05, 0.012, LN.IRON, 16, 6, p => rotX(p, Math.PI / 2));
  // Candle: wax pillar with a little drip ring; the flame is a VFX.
  tube(m, [[0, 0.05, 0], [0, LANTERN_FLAME_Y - 0.01, 0]], [0.055, 0.052], LN.WAX, 12);
  torus(m, [0, LANTERN_FLAME_Y - 0.03, 0], 0.052, 0.012, LN.WAX, 12, 5);
  // Warm glowing inner floor so the base reads as lit from the candle.
  box(m, [0, 0.05, 0], [W - 0.02, 0.004, W - 0.02], 0, { side: LN.GLOW, top: LN.GLOW }, 1);
  return m;
}

// ── Textures ─────────────────────────────────────────────────────────────────
function hash(x, y) { let h = (x * 374761393 + y * 668265263) | 0; h = (h ^ (h >>> 13)) * 1274126177; return ((h ^ (h >>> 16)) >>> 0) / 4294967295; }
function smoothNoise(x, y) {
  const xi = Math.floor(x), yi = Math.floor(y), xf = x - xi, yf = y - yi;
  const s = t => t * t * (3 - 2 * t);
  const a = hash(xi, yi), b = hash(xi + 1, yi), c = hash(xi, yi + 1), d = hash(xi + 1, yi + 1);
  return a + (b - a) * s(xf) + (c - a) * s(yf) + (a - b - c + d) * s(xf) * s(yf);
}
const fbm = (x, y) => 0.5 * smoothNoise(x, y) + 0.25 * smoothNoise(2 * x, 2 * y) + 0.125 * smoothNoise(4 * x, 4 * y);
const mix = (a, b, t) => a.map((v, i) => v + (b[i] - v) * t);
const inRect = (r, u, v) => u >= r.u0 && u < r.u1 && v >= r.v0 && v < r.v1;
const local = (r, u, v) => [(u - r.u0) / (r.u1 - r.u0), (v - r.v0) / (r.v1 - r.v0)];

function paint(fn) {
  const rgba = Buffer.alloc(TEX * TEX * 4);
  for (let y = 0; y < TEX; y++) for (let x = 0; x < TEX; x++) {
    const u = (x + 0.5) / TEX, v = 1 - (y + 0.5) / TEX, c = fn(u, v, x, y);
    const i = (y * TEX + x) * 4;
    for (let k = 0; k < 3; k++) rgba[i + k] = Math.max(0, Math.min(255, Math.round(c[k])));
    rgba[i + 3] = 255;
  }
  return rgba;
}

// Packed snow is not paper white: kept below ~0.9 albedo so it doesn't bloom
// under the town lights, with cool blue-grey shading and a few glints.
function snowColor(u, v, x, y) {
  const n = fbm(u * 24, v * 24), fine = fbm(u * 120, v * 120);
  let c = mix([176, 188, 206], [226, 231, 238], 0.35 + 0.65 * n);
  c = c.map(ch => ch * (0.96 + 0.06 * fine));
  if (hash(x * 3 + 1, y * 7 + 5) > 0.994) c = [246, 248, 252];
  return c;
}

const PAINT = {
  snowman: (u, v, x, y) => {
    if (inRect(SM.SNOW, u, v)) return snowColor(u, v, x, y);
    if (inRect(SM.CARROT, u, v)) {
      const [s, t] = local(SM.CARROT, u, v);
      const ridge = 0.85 + 0.15 * Math.abs(Math.sin(t * 40 + fbm(s * 8, t * 8) * 2));
      return mix([222, 104, 22], [240, 140, 40], fbm(s * 20, t * 10)).map(ch => ch * ridge);
    }
    if (inRect(SM.TWIG, u, v)) {
      const [s, t] = local(SM.TWIG, u, v);
      return mix([62, 44, 30], [104, 76, 52], fbm(s * 30, t * 6)).map(ch => ch * (0.85 + 0.15 * Math.sin(s * 60)));
    }
    if (inRect(SM.SCARF, u, v)) {
      const [s, t] = local(SM.SCARF, u, v);
      const stripe = Math.floor(s * 18) % 3;
      const base = [[186, 28, 36], [236, 230, 218], [30, 110, 60]][stripe];
      const knit = 0.84 + 0.16 * Math.abs(Math.sin(s * 18 * 12 * Math.PI)) * Math.abs(Math.sin(t * 10 * Math.PI));
      return base.map(ch => ch * knit);
    }
    if (inRect(SM.BAND, u, v)) return mix([150, 20, 28], [184, 34, 40], fbm(u * 60, v * 60));
    if (inRect(SM.HAT, u, v)) return mix([22, 22, 26], [42, 40, 46], fbm(u * 40, v * 40));
    if (inRect(SM.COAL, u, v)) return mix([16, 16, 18], [46, 44, 44], fbm(u * 90, v * 90));
    return [128, 128, 128];
  },
  gifts: (u, v) => {
    for (let k = 0; k < 3; k++) {
      const side = GIFT_SIDE(k), top = GIFT_TOP(k);
      if (!inRect(side, u, v) && !inRect(top, u, v)) continue;
      const w = WRAPS[k], isTop = inRect(top, u, v);
      const [s, t] = local(isTop ? top : side, u, v);
      const onRibbon = Math.abs(s - 0.5) < RIBBON / 2 || (isTop && Math.abs(t - 0.5) < RIBBON / 2);
      if (onRibbon) {
        const edge = Math.min(Math.abs(Math.abs(s - 0.5) - RIBBON / 2), isTop ? Math.abs(Math.abs(t - 0.5) - RIBBON / 2) : 1);
        const sheen = 0.9 + 0.1 * Math.sin((s + t) * 40);
        return w.ribbon.map(ch => ch * sheen * (edge < 0.01 ? 0.8 : 1));
      }
      let c = w.wrap.map(ch => ch * (0.92 + 0.08 * fbm(s * 30, t * 30)));
      const light = w.wrap[0] > 200 ? [196, 40, 44] : mix(w.wrap, [255, 240, 210], 0.55);
      if (w.pattern === 'dots') {
        const gx = s * 7, gy = t * 7 + (Math.floor(s * 7) % 2) * 0.5;
        if (Math.hypot(gx - Math.floor(gx) - 0.5, gy - Math.floor(gy) - 0.5) < 0.16) c = light;
      } else if (w.pattern === 'stripes') {
        if (((s + t) * 9) % 1 < 0.22) c = mix(c, light, 0.75);
      } else {
        // Little five-point stars on a grid.
        const gx = s * 6, gy = t * 6, fx = gx - Math.floor(gx) - 0.5, fy = gy - Math.floor(gy) - 0.5;
        const a = Math.atan2(fy, fx), r = Math.hypot(fx, fy);
        if (r < 0.2 * (0.55 + 0.45 * Math.cos(5 * a))) c = mix(light, [214, 170, 60], 0.3);
      }
      return c;
    }
    return [128, 128, 128];
  },
  lantern: (u, v) => {
    if (inRect(LN.IRON, u, v)) {
      const n = fbm(u * 50, v * 50);
      let c = mix([30, 30, 34], [58, 56, 58], n);
      if (fbm(u * 14 + 3, v * 14) > 0.66) c = mix(c, [96, 58, 34], 0.5); // a little rust
      return c;
    }
    if (inRect(LN.WAX, u, v)) return mix([232, 222, 196], [246, 240, 222], fbm(u * 30, v * 30));
    return [255, 200, 110]; // warm glow
  },
};

async function preview(objFile, rgba, pngFile, { yaw, pitch }) {
  const mesh = loadObj(objFile);
  // The rasteriser frames about one unit round y = 0.3: fit the prop to that.
  const ys = mesh.v.map(p => p[1]), k = 0.95 / Math.max(Math.max(...ys) - Math.min(...ys), ...mesh.v.map(p => 1.6 * Math.hypot(p[0], p[2])));
  mesh.v = mesh.v.map(([x, y, z]) => [x * k, (y - Math.min(...ys)) * k - 0.17, z * k]);
  const img = render(mesh, { rgba, width: TEX, height: TEX }, { size: 420, yaw, pitch });
  await sharp(img, { raw: { width: 420, height: 420, channels: 4 } }).png().toFile(pngFile);
}

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const work = fs.mkdtempSync(path.join(OUT, '.work-'));
  try {
    for (const [kind, build] of [['snowman', snowman], ['gifts', gifts], ['lantern', lantern]]) {
      const mesh = build();
      const objName = `${kind}.obj`;
      fs.writeFileSync(path.join(OUT, objName), mesh.obj(`D2RR winter ${kind}`));
      fs.copyFileSync(path.join(OUT, objName), path.join(work, objName));
      const ext = [0, 1, 2].map(i => Math.max(...mesh.v.map(p => Math.abs(p[i]))));
      const rgba = paint(PAINT[kind]);
      await sharp(rgba, { raw: { width: TEX, height: TEX, channels: 4 } }).png().toFile(path.join(OUT, `${kind}_alb.png`));
      await preview(path.join(OUT, objName), rgba, path.join(OUT, `${kind}_preview.png`), { yaw: 0.35, pitch: 0.45 });
      fs.writeFileSync(path.join(OUT, `${kind}_alb.texture`), buildBC3Texture(rgba, TEX, TEX));
      if (D2RPP) convert({ d2rpp: D2RPP, template: TEMPLATE, objFile: objName, albedoPath: TEXTURE_PATHS[kind], modelFile: path.join(OUT, `${kind}_lod0.model`), work });
      console.log(`${kind}: ${mesh.v.length} verts, ${mesh.f.length} tris, extent ${ext.map(x => x.toFixed(2)).join('/')}${D2RPP ? ', model built' : ' (no --d2rpp: model skipped)'}`);
    }
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

