//
//   node scripts/build-winter-assets.mjs --d2rpp <path to d2rpp.exe> [--out data/winter/assets]
//
// Same pipeline as build-autumn-assets.mjs: meshes are generated procedurally
// as OBJ, textures are painted in code and encoded to D2R's BC3 .texture
// format (scripts/lib/d2r-texture.mjs), and each model is built by
// transplanting the mesh into a vanilla prop (scripts/lib/model-transplant.mjs).
// Without --d2rpp only the OBJs and textures are written (plus previews).
//
// Conventions: Y-up, sitting on y = 0, facing +Z at yaw 0 (placement yaw 45°
// turns it toward the camera). Every triangle is wound counter-clockwise
// around its vertex normals, as in vanilla models. OBJ-style UVs (v = 0 is the
// bottom row of the texture).
